"""Точка входа консольного приложения."""


class WalletApplication:
    """Консольное приложение валютного кошелька."""

    def run(self) -> None:
        """Показать приветствие подготовленного приложения."""
        print("Валютный кошелёк")
        print("Окружение готово. Команды кошелька появятся на следующих этапах.")


def main() -> None:
    """Запустить приложение."""
    app = WalletApplication()
    app.run()


if __name__ == "__main__":
    main()
